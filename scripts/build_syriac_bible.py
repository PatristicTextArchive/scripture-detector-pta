#!/usr/bin/env python3
"""Build data/syriac/{bible.tsv, book_mapping.tsv, LICENSES.md} from the Syriac
Bible texts (Peshitta) of the Patristic Text Archive.

Source: https://github.com/PatristicTextArchive/pta_data  (data/pta9999/*/*-syc1.xml)
        Old Testament and deuterocanonical books: ETCBC/peshitta (version 0.5),
        licence CC BY-NC 4.0 (non-commercial!).  New Testament: Gwilliam / Pinkerton /
        Gwynn (1905), TEI edition by James E. Walters, licence stated in the files as
        CC BY-SA 4.0.  The licence of every book is written to LICENSES.md.

Usage:
    python scripts/build_syriac_bible.py --pta-data /path/to/pta_data
    python scripts/build_syriac_bible.py --download

Internal book codes are the lower-cased PTA abbreviations (the same as for the
Greek Bible); the corpus prefix in references is Peshitta (Peshitta:Gn:1:1).  Chapter and
verse numbers are those of the Peshitta files (Psalms: Hebrew numbering).
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
import tempfile
from pathlib import Path

from lxml import etree

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_greek_bible as g  # noqa: E402  (verse extraction and the PTA book table)

TEI = g.TEI

# Books that differ from the Greek table (pta id -> (abbr, testament, English name)).
OVERRIDES = {
    "015": ("PrMan", "ap", "Prayer of Manasseh"),
    "016": ("Esr", "ot", "Ezra"),
    "017": ("Neh", "ot", "Nehemiah"),
    "018": ("3Esr", "ap", "1 Esdras (3 Esdras)"),
    "019": ("4Esr", "ap", "4 Ezra (2 Esdras)"),
    "057": ("2Bar", "ap", "2 Baruch (Syriac Apocalypse of Baruch, with the Letter of Baruch, chapters 78-87)"),
    "058": ("2Bar", "ap", "2 Baruch (Syriac Apocalypse of Baruch, with the Letter of Baruch, chapters 78-87)"),
}


def books():
    """(pta id, abbr, testament, name) for every Syriac book, in canonical order."""
    table = {b[0]: b for b in g.BOOKS}
    ids = sorted(set(table) | set(OVERRIDES))
    for wid in ids:
        if wid in OVERRIDES:
            abbr, test, name = OVERRIDES[wid]
        else:
            _, abbr, _corpus, test, name, _gname = table[wid]
        yield wid, abbr, test, name


def licence_of(path: Path) -> tuple[str, str]:
    root = etree.parse(str(path)).getroot()
    lic = root.find(f".//{TEI}licence")
    text = re.sub(r"\s+", " ", "".join(lic.itertext())).strip() if lic is not None else "not stated"
    src = root.find(f".//{TEI}sourceDesc//{TEI}title")
    title = re.sub(r"\s+", " ", "".join(src.itertext())).strip() if src is not None else "not stated"
    return text, title


def clean(txt: str) -> str:
    txt = txt.replace("\\n", " ")                       # literal "\n" in some New Testament verses
    return re.sub(r"\s+", " ", txt).strip()


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--pta-data", type=Path)
    ap.add_argument("--download", action="store_true")
    ap.add_argument("--out", type=Path, default=Path(__file__).resolve().parent.parent / "data" / "syriac")
    args = ap.parse_args()
    src = args.pta_data
    if args.download:
        tmp = Path(tempfile.mkdtemp())
        subprocess.run(["git", "clone", "--depth", "1",
                        "https://github.com/PatristicTextArchive/pta_data.git", str(tmp)], check=True)
        src = tmp
    if not src:
        ap.error("give --pta-data PATH or --download")
    base = src / "data" / "pta9999"
    args.out.mkdir(parents=True, exist_ok=True)

    n_verses = 0
    seen_books: dict[str, str] = {}
    licences: dict[str, set] = {}
    with open(args.out / "bible.tsv", "w", encoding="utf-8") as fb:
        fb.write("testament\twork_name\tbook_code\tchapter_number\tverse_index\ttext\n")
        for wid, abbr, test, name in books():
            f = base / f"pta{wid}" / f"pta9999.pta{wid}.pta-syc1.xml"
            if not f.exists():
                print(f"missing: {f}", file=sys.stderr)
                continue
            code = abbr.lower()
            seen_books.setdefault(code, f"{test}\t{name}\t\t{code}\t{abbr}\tPES")
            lic, title = licence_of(f)
            licences.setdefault(f"{title} | {lic}", set()).add(name)
            for chap, verse, txt in g.read_book(f):
                txt = clean(txt)
                if txt:
                    fb.write(f"{test}\t{name}\t{code}\t{chap}\t{verse}\t{txt}\n")
                    n_verses += 1
    with open(args.out / "book_mapping.tsv", "w", encoding="utf-8") as fm:
        fm.write("testament\twork_name\tgreek_name\tbook_code\tpta_abbr\tpta_corpus\n")
        for line in seen_books.values():
            fm.write(line + "\n")
    with open(args.out / "LICENSES.md", "w", encoding="utf-8") as fl:
        fl.write("# Licences of the Syriac Bible texts\n\n"
                 "Generated by `scripts/build_syriac_bible.py` from the Patristic Text Archive "
                 "(https://github.com/PatristicTextArchive/pta_data, `data/pta9999`, `*-syc1.xml`).\n\n"
                 "**The Old Testament and deuterocanonical texts are licensed for non-commercial use only (CC BY-NC 4.0).**\n\n")
        for key, names in sorted(licences.items()):
            title, lic = key.split(" | ", 1)
            fl.write(f"## {title}\n\n{lic}\n\nBooks: {', '.join(sorted(names))}\n\n")
    print(f"wrote {n_verses} verses in {len(seen_books)} books to {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
